# The ledger is APPEND-ONLY, so a void is itself an appended row rather than an edit.
# The entry keeps its integrity hash and stays readable; it simply stops counting.
def void_entry(entry_id: str, reason: str, by: str = "",
               ledger_path: Path = DEFAULT_LEDGER) -> dict:
    """Mark an entry as not-evidence. Append-only; the original row is untouched."""
    if not reason.strip():
        raise ValueError("REFUSED: a void needs a stated reason — an unexplained "
                         "void is indistinguishable from deleting a losing trade")
    rec = {"type": "void", "entry_id": entry_id, "reason": reason, "by": by,
           "logged_at": datetime.now(timezone.utc).isoformat()}
    _append(Path(ledger_path), rec)
    return rec


def voided(ledger_path: Path = DEFAULT_LEDGER) -> dict:
    """entry_id -> reason, for every voided entry."""
    return {r["entry_id"]: r.get("reason", "")
            for r in _read(ledger_path) if r.get("type") == "void"}


def stats(ledger_path: Path = DEFAULT_LEDGER) -> dict:
    rows = _read(ledger_path)
    entries = [r for r in rows if r.get("type") == "entry"]
    outcomes = {}
    for r in rows:                                   # last outcome per entry wins
        if r.get("type") == "outcome":
            outcomes[r["entry_id"]] = r

    # VOIDED entries are excluded from every statistic below, but their COUNT is
    # reported — a record that hides its own exclusions is trusted more than it
    # deserves to be, which is the same reasoning behind the backfill flag.
    void_map = voided(ledger_path)

    # trades = entries whose verdict was an actual BUY/SHORT
    trades = [e for e in entries
              if e["verdict"]["action"] in ("BUY", "SHORT") and e["id"] not in void_map]
    n_voided_trades = sum(1 for e in entries
                          if e["verdict"]["action"] in ("BUY", "SHORT") and e["id"] in void_map)
    joined = [(e, outcomes[e["id"]]) for e in trades if e["id"] in outcomes]
    normal = [(e, o) for (e, o) in joined if o.get("classification") == "NORMAL"
              and o.get("idio_sign_correct") is not None]

    n = len(normal)
    correct = sum(1 for _, o in normal if o["idio_sign_correct"])
    acc = (correct / n) if n else None

    # ---- EXPECTANCY (v1.5.7, external review #3) -----------------------------
    # THE DEFECT THIS FIXES. Every statistic in this model was a SIGN statistic —
    # 5/15, 8/14, "idio-sign < 50% -> PAUSE". Not one was P&L. For a gap-capture
    # strategy that is the wrong axis, and the model already knows the argument: it
    # cut `value` because option richness "forecasts MAGNITUDE and carries no
    # information about SIGN", then built its entire scorecard on sign and threw
    # magnitude away.
    #
    # 5/15 at a 3:1 payoff is a good system. 5/15 at 1:1 is a dead one. Until now
    # NOTHING HERE COULD TELL THOSE APART — and the kill switch inherits the defect:
    # `idio-sign < 50% at n>=15 -> PAUSE` fires on a profitable model and stays
    # silent on an unprofitable one.
    #
    # Measured on the live ledger the day this shipped: hit rate 33.3%, payoff 1.18,
    # expectancy -2.15% per trade, -32.2% cumulative. The sign record said "5/15,
    # nothing validated". The expectancy record says something materially worse, and
    # it was computable from these same rows the whole time.
    signed = []
    for e, o in normal:
        idio = o.get("idio_open_pct")
        if idio is None:
            continue
        signed.append(idio if e["verdict"]["action"] == "BUY" else -idio)
    wins = [s for s in signed if s > 0]
    losses = [s for s in signed if s <= 0]
    avg_win = (sum(wins) / len(wins)) if wins else None
    avg_loss = (abs(sum(losses) / len(losses))) if losses else None
    expectancy = (sum(signed) / len(signed)) if signed else None
    payoff = (avg_win / avg_loss) if (avg_win and avg_loss) else None
    # EXPECTANCY EXCLUDING THE SINGLE LARGEST WINNER (review #3 follow-up). At 4-5 wins
    # in 11-15 trades, expectancy is dominated by one tail. This one line answers
    # "do we have a strategy, or do we have AEHR?" — and it is the number that decides
    # whether a positive expectancy is worth anything at this sample size.
    ex_top = None
    if len(signed) > 1:
        trimmed = sorted(signed)[:-1]
        ex_top = sum(trimmed) / len(trimmed)

    # INDEPENDENCE-ADJUSTED n (external review #3). The error ledger counts distinct
    # (sector, event_date) keys precisely because same-night names are one observation.
    # That rule was never applied to the model's OWN accuracy stats, which is where it
    # matters most: 14 forecasts spanning 2 event-dates is n=2, not n=14. Both numbers
    # are reported from here on; quoting only the raw one overstates the sample.
    n_days = len({e.get("event_date") for e, _ in normal})

    # HOLD-TO-CLOSE SHADOW (v1.5.1): parallel accuracy at the close horizon, plus the
    # mean |gap| vs |close| move on ALL scored outcomes (trades + no-trades) — the latter
    # is the evidence for whether the overnight gap or the full day is where alpha lives.
    close_trades = [(e, o) for (e, o) in normal if o.get("close_sign_correct") is not None]
    n_close = len(close_trades)
    close_correct = sum(1 for _, o in close_trades if o["close_sign_correct"])
    acc_close = (close_correct / n_close) if n_close else None
    horizon = [o for o in outcomes.values()
               if o.get("idio_close_pct") is not None and o.get("idio_open_pct") is not None]
    mean_abs_gap = (sum(abs(o["idio_open_pct"]) for o in horizon) / len(horizon)) if horizon else None
    mean_abs_close = (sum(abs(o["idio_close_pct"]) for o in horizon) / len(horizon)) if horizon else None

    # by conviction tier
    def tier_acc(tier):
        sub = [(e, o) for (e, o) in normal if _conv(e["verdict"].get("conviction")) == tier]
        c = sum(1 for _, o in sub if o["idio_sign_correct"])
        return len(sub), (c / len(sub) if sub else None)
    n_high, acc_high = tier_acc("HIGH")
    n_med, acc_med = tier_acc("MEDIUM")
    n_low, acc_low = tier_acc("LOW")

    # per-component standalone hit (nonzero contributions, NORMAL trades)
    comp = {}
    for c in COMPONENTS:
        nz = [(e, o) for (e, o) in normal if e["verdict"]["components"].get(c, 0) != 0]
        hits = sum(1 for e, o in nz
                   if _sign(e["verdict"]["components"][c]) == _sign(o["idio_open_pct"]))
        comp[c] = {"n": len(nz), "hit": (hits / len(nz) if nz else None)}

    # Type-B rate in last 10 outcomes (by time)
    outs_sorted = sorted(outcomes.values(), key=lambda o: o["logged_at"])
    last10 = outs_sorted[-10:]
    type_b = sum(1 for o in last10 if o.get("taxonomy") == "B")

    # Stage-1 skew coverage toward the Stage-2 n>=10 bar
    skew_logged = [e for e in entries if e["verdict"].get("skew") is not None]
    # Stage-2 veto-candidate evidence: traded + outcome where skew would veto
    veto_cand = []
    for e, o in normal:
        sk = e["verdict"].get("skew")
        act = e["verdict"]["action"]
        if sk is None:
            continue
        if (act == "BUY" and sk <= -2) or (act == "SHORT" and sk >= +2):
            veto_cand.append((e, o))
    veto_correct = sum(1 for _, o in veto_cand if o["idio_sign_correct"])

    # NO-TRADE subtype "would-have-worked" (paper): needs outcome logged on a no-trade
    return {
        "engine_version": ENGINE_VERSION,
        "n_entries": len(entries), "n_trades": len(trades), "n_outcome": n,
        "n_voided_trades": n_voided_trades, "voided": void_map,
        "accuracy": acc, "correct": correct,
        # EXPECTANCY — the axis the sign statistics above cannot see. See the block
        # in stats() for why a hit rate alone cannot distinguish a good system from
        # a dead one, and why the kill switches were blind in both directions.
        "expectancy_pct": expectancy, "expectancy_ex_top_pct": ex_top,
        "avg_win_pct": avg_win, "avg_loss_pct": avg_loss,
        "payoff_ratio": payoff, "total_idio_pct": (sum(signed) if signed else None),
        # INDEPENDENCE-ADJUSTED n: same-night names are ONE observation, the rule the
        # error ledger already enforces and the scorecard never did.
        "n_event_days": n_days,
        "n_high": n_high, "acc_high": acc_high, "n_med": n_med, "acc_med": acc_med,
        "n_low": n_low, "acc_low": acc_low,
        "n_close": n_close, "acc_close": acc_close,
        "mean_abs_gap": mean_abs_gap, "mean_abs_close": mean_abs_close,
        "n_circular": sum(1 for _, o in normal if o.get("benchmark_circular")),
        "overrides": overrides(ledger_path),
        "components": comp, "type_b_last10": type_b,
        "skew_logged": len(skew_logged), "stage2_bar": 10,
        "veto_candidates": len(veto_cand),
        "veto_candidate_acc": (veto_correct / len(veto_cand) if veto_cand else None),
        "awaiting_outcome": [e["id"] for e in trades if e["id"] not in outcomes],
    }


def kill_switches(s: dict) -> list:
    """Evaluate §9 kill switches + additions. Returns list of (name, status, detail)."""
    out = []

    def add(name, tripped, detail):
        out.append((name, "PAUSE" if tripped else "ok", detail))

    n, acc = s["n_outcome"], s["accuracy"]
    exp = s.get("expectancy_pct")

    # ---- SIGN x EXPECTANCY, v1.5.7 -------------------------------------------------
    # The old switch read SIGN ONLY, and sign cannot see the thing that matters: it
    # fires on a profitable model and stays silent on an unprofitable one.
    #
    # But swapping sign FOR expectancy is the wrong correction. At n~15 expectancy is
    # dominated by a single tail (AEHR is +35% in an 11-trade record), so a raw
    # expectancy trigger gets jerked around by one print. Use BOTH, structurally:
    #
    #   both bad          -> PAUSE.    No ambiguity.
    #   they DISAGREE     -> REVIEW, never an automatic pause. In particular:
    #     sign<50% + expectancy>0 is THE EXPECTED PROFILE FOR GAP CAPTURE — few large
    #       winners paying for many small losers. Killing that on a sign switch is how
    #       you shut down a working strategy.
    #     sign>50% + expectancy<0 is picking up pennies, and it is the MORE dangerous
    #       of the two because the sign dashboard reads green the whole way down.
    both_bad = (n >= 15 and acc is not None and acc < 0.50
                and exp is not None and exp <= 0)
    add("expectancy<=0 AND idio-sign<50% @ n>=15", both_bad,
        f"n={n}, acc={_pct(acc)}, expectancy={exp:+.2f}%" if exp is not None
        else f"n={n}, acc={_pct(acc)}, expectancy=n/a")
    if n >= 15 and acc is not None and exp is not None and not both_bad:
        if acc < 0.50 and exp > 0:
            out.append(("sign<50% but expectancy>0", "REVIEW",
                        f"acc={_pct(acc)}, expectancy={exp:+.2f}% — the EXPECTED gap-capture "
                        f"profile (few large winners). Do NOT pause on sign alone."))
        elif acc >= 0.50 and exp <= 0:
            out.append(("sign>=50% but expectancy<=0", "REVIEW",
                        f"acc={_pct(acc)}, expectancy={exp:+.2f}% — picking up pennies. "
                        f"MORE dangerous than the reverse: the sign dashboard reads green."))
    ex_top = s.get("expectancy_ex_top_pct")
    if ex_top is not None and exp is not None:
        out.append(("expectancy excl. largest winner", "info",
                    f"{exp:+.2f}% -> {ex_top:+.2f}% without the top trade"
                    + ("   <-- the edge IS one trade" if exp > 0 >= ex_top else "")))
    add("slow degrade <55% @ n>=30",
        (n >= 30 and acc is not None and acc < 0.55),
        f"n={n}, acc={_pct(acc)}")
    for c, d in s["components"].items():
        if d["n"] >= 20 and d["hit"] is not None and d["hit"] < 0.50:
            out.append((f"component {c} <50% @ n>=20", "ABLATE",
                        f"n={d['n']}, hit={_pct(d['hit'])}"))
    add("Type-B >2/10 (SAT recalibrate)", s["type_b_last10"] > 2,
        f"{s['type_b_last10']}/10 in last 10 outcomes")
    inv = (s["n_high"] >= 10 and s["acc_high"] is not None and s["acc_med"] is not None
           and s["acc_high"] < s["acc_med"])
    add("HIGH<MEDIUM tier inversion @ n_HIGH>=10", inv,
        f"HIGH {_pct(s['acc_high'])} (n={s['n_high']}) vs MED {_pct(s['acc_med'])} (n={s['n_med']})")
    return out


def _pct(x):
    return "n/a" if x is None else f"{x*100:.0f}%"


def render_stats(s: dict) -> str:
    L = []
    L.append(f"PRE ledger - engine v{s['engine_version']}")
    L.append(f"  entries={s['n_entries']}  trades={s['n_trades']}  outcomes(NORMAL)={s['n_outcome']}")
    L.append(f"  idio-sign accuracy: {_pct(s['accuracy'])}  ({s['correct']}/{s['n_outcome']})"
             f"   [benchmark to beat ~50pct / straddle, net]")
    L.append(f"  by conviction:  HIGH {_pct(s['acc_high'])} (n={s['n_high']})   "
             f"MEDIUM {_pct(s['acc_med'])} (n={s['n_med']})   "
             f"LOW {_pct(s['acc_low'])} (n={s['n_low']})")
    if s.get("mean_abs_gap") is not None:
        L.append(f"  HORIZON SHADOW: gap-exit acc {_pct(s['accuracy'])} vs close-exit "
                 f"{_pct(s['acc_close'])} (n_close={s['n_close']})   "
                 f"mean|idio| gap {s['mean_abs_gap']:.2f}% vs close {s['mean_abs_close']:.2f}% "
                 f"-> {'CLOSE holds the move' if (s['mean_abs_close'] or 0) > 1.5*(s['mean_abs_gap'] or 1) else 'comparable'}")
    ov = s["overrides"]
    L.append(f"  narrative overrides: {ov['n']} logged, {ov['n_scored']} scored, "
             f"helped {_pct(ov['helped_rate'])}"
             + (f"  [OPEN: {', '.join(ov['open'][:4])}]" if ov["open"] else ""))
    if s["n_circular"]:
        L.append(f"  !! {s['n_circular']} outcome(s) use a CIRCULAR benchmark "
                 f"(name >{BENCH_DOMINANCE_MAX_PCT}% of its own ETF) — re-benchmark before use")
    L.append("  per-component standalone hit:")
    for c, d in s["components"].items():
        L.append(f"      {c:5s} n={d['n']:<3d} hit={_pct(d['hit'])}")
    L.append(f"  Stage-1 skew logged: {s['skew_logged']} / {s['stage2_bar']} "
             f"toward Stage-2 veto bar")
    L.append(f"  Stage-2 veto candidates: {s['veto_candidates']}  "
             f"their idio-sign acc={_pct(s['veto_candidate_acc'])}  "
             f"(low acc = evidence FOR the veto)")
    L.append("  kill switches:")
    for name, status, detail in kill_switches(s):
        L.append(f"      [{status:6s}] {name}  - {detail}")
    if s["awaiting_outcome"]:
        L.append(f"  awaiting outcome ({len(s['awaiting_outcome'])}): "
                 + ", ".join(s["awaiting_outcome"][:8])
                 + (" ..." if len(s["awaiting_outcome"]) > 8 else ""))
    L.append("  NOTE: n~3 - nothing is validated. This dashboard accrues the forward sample; "
             "no LOGIC change lands until its evidence bar clears.")
    return "\n".join(L)


