def _show(n, ledger_path=DEFAULT_LEDGER):
    entries = [r for r in _read(ledger_path) if r.get("type") == "entry"]
    for e in entries[-n:]:
        v = e["verdict"]
        layer = v.get("layer", "sign")
        conv = v.get("conviction", "") or ""
        if "ds" in v:
            core = (f"DS={v['ds']:+d}[{v.get('ds_floor', 0):+d},{v.get('ds_ceil', 0):+d}] "
                    f"SKEW={v.get('skew')} sens={v.get('sensitivity')}")
        else:
            rd = v.get("reads", {})
            core = (f"{v.get('asymmetry', ''):8s} IRM={rd.get('irm')} "
                    f"{v.get('shares', 0)}sh gar=${v.get('gap_at_risk', 0):,.0f}")
        ex = v.get("exit") or {}
        exs = f"  enter {ex.get('entry_close_date')}->exit {ex.get('exit_open_date')}" if ex.get("exit_open_date") else ""
        print(f"{e['id']:<26s} {v['action']:<9s} {conv:<5s} [{layer:9s}] {core}{exs}")


