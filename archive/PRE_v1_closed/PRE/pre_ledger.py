"""
PRE ledger — frozen pre-registration + append-only outcome log + kill-switch stats.
================================================================================
Implements §14.G step 7 (freeze pre-registration with integrity_hash), C11 (append-only,
never overwrite) and §9 (idio-sign accuracy, per-component standalone hit, Type-B rate,
conviction calibration) plus the Stage-1 skew n-count toward the Stage-2 bar.

Three row types in ledger.jsonl:
  {"type":"entry",    ...}  — a frozen pre-registration (integrity-hashed decision).
  {"type":"outcome",  ...}  — a post-event result, keyed by entry_id (append-only; the
                              LAST outcome per entry_id wins, so corrections are additive).
  {"type":"override", ...}  — (v1.5.0) a NARRATIVE override of a mechanical signal. Logged
                              and scored as a decision in its own right; see log_override().

Nothing here fetches or trades. Outcomes are supplied by the caller after the print.

CLI:
  python pre_ledger.py stats          # kill-switch dashboard
  python pre_ledger.py show [N]       # last N entries (default 10)
  python pre_ledger.py outcomes       # entries still awaiting an outcome
  python pre_ledger.py overrides      # narrative overrides and how they scored
"""
