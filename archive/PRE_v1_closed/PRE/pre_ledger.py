# --------------------------------------------------------------------------- io
def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _canonical(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str)


def _hash(payload) -> str:
    return "sha256:" + hashlib.sha256(_canonical(payload).encode()).hexdigest()


def _dc(x):
    return asdict(x) if x is not None else None


def _append(path: Path, record: dict) -> None:
    from pre_closed import assert_open
    assert_open(path, DEFAULT_LEDGER)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record, default=str) + "\n")


def _read(path: Path):
    if not Path(path).exists():
        return []
    rows = []
    with Path(path).open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def _sign(x) -> int:
    return 1 if x > 0 else (-1 if x < 0 else 0)


# Conviction vocabulary is HIGH / MEDIUM / LOW / NONE. The calc-risk layer historically
# emitted "MED", which silently never matched the "MEDIUM" key here — so calc-risk tier
# calibration was being computed on an empty set. calc-risk v1.1.0 emits MEDIUM; this
# normaliser keeps the ALREADY-WRITTEN rows readable (the ledger is append-only).
_CONV_ALIAS = {"MED": "MEDIUM", "M": "MEDIUM", "HI": "HIGH"}


def _conv(v) -> str:
    v = (v or "NONE").upper()
    return _CONV_ALIAS.get(v, v)


# Benchmark de-circularization: a name that dominates its own sector ETF cannot be
# beta-stripped against it — subtracting the ETF partly subtracts the stock's own move,
# so "idiosyncratic" return is understated. Callers pass the name's index weight; above
# this the outcome is flagged CIRCULAR and an alternative benchmark is required.
BENCH_DOMINANCE_MAX_PCT = 15.0


