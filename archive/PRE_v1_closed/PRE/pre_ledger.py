def pre_register(ticker: str, judgment: Judgment, market: Market,
                 truth: Optional[Truth] = None, skew: Optional[Skew] = None,
                 cfg: Optional[EngineConfig] = None, event_date: Optional[str] = None,
                 note: str = "", ledger_path: Path = DEFAULT_LEDGER,
                 allow_paused: bool = False) -> dict:
    """Run the engine, FREEZE the decision with an integrity hash, append to the ledger.
    Returns the full record (including its id and integrity_hash)."""
    paused = trade_paused()
    if paused and not allow_paused:
        raise RuntimeError(
            f"TRADE REGISTRATION IS PAUSED since {paused['since']}.\n"
            f"  REASON: {paused['reason']}\n"
            f"  SCOPE:  {paused['scope']}\n"
            f"  RESUME CONDITIONS:\n    "
            + "\n    ".join(paused["resume_conditions"])
            + "\n  The FORECAST layer is unaffected — run it, it is graded on every event.")
    cfg = cfg or EngineConfig()
    res = evaluate(judgment, market, t=truth, cfg=cfg, skew=skew)

    inputs = {"judgment": _dc(judgment), "market": _dc(market),
              "truth": _dc(truth), "skew": _dc(skew), "cfg": _dc(cfg)}
    verdict = {
        "action": res.action, "ds": res.ds, "ds_floor": res.ds_floor, "ds_ceil": res.ds_ceil,
        "conviction": res.conviction, "components": res.components,
        "unavailable": res.unavailable, "no_trade_subtype": res.no_trade_subtype,
        "shares": res.shares, "gap_at_risk": res.gap_at_risk, "final_units": res.final_units,
        "sensitivity": res.sensitivity, "warnings": res.warnings,
        "skew": res.skew, "skew_components": res.skew_components, "skew_status": res.skew_status,
    }
    frozen = {"schema": SCHEMA, "engine_version": ENGINE_VERSION, "ticker": ticker,
              "event_date": event_date or _now()[:10], "inputs": inputs, "verdict": verdict}
    ih = _hash(frozen)                       # hash the DECISION payload only (no timestamp)
    entry_id = f"{ticker}:{frozen['event_date']}:{ih[7:15]}"
    record = {"type": "entry", "id": entry_id, "logged_at": _now(), "note": note,
              **frozen, "integrity_hash": ih}
    _append(ledger_path, record)
    return record


def record_outcome(entry_id: str, stock_open_pct: float, etf_open_pct: float,
                   classification: str = "NORMAL", taxonomy: Optional[str] = None,
                   note: str = "", ledger_path: Path = DEFAULT_LEDGER,
                   benchmark: Optional[str] = None,
                   benchmark_weight_pct: Optional[float] = None,
                   stock_close_pct: Optional[float] = None,
                   etf_close_pct: Optional[float] = None,
                   beta: Optional[float] = None) -> dict:
    """Append a post-event outcome. idio_open = stock_open − etf_open (beta-stripped).
    classification NORMAL/ANOMALY (ANOMALY is frozen out of tuning stats, §9).
    taxonomy A–F (use 'B' for a saturation-misread — feeds the Type-B kill switch).

    HONESTY NOTE (do not soften in any writeup): this is a market-ADJUSTED return with
    beta ASSUMED = 1. There is no estimation window and no test statistic. It is not an
    event study and it computes no statistical significance.

    benchmark / benchmark_weight_pct (v1.5.0): the ETF used and the name's weight in it.
    Above BENCH_DOMINANCE_MAX_PCT the subtraction is CIRCULAR (e.g. a mega-cap versus its
    own sector ETF) and the row is flagged so it can be excluded or re-benchmarked.

    HOLD-TO-CLOSE SHADOW (v1.5.1, PLUMBING — measurement only, changes NO decision):
    the model's live exit is the first OPEN after the print (gap capture). But repeated
    post-mortems (2026-07-24, 2026-07-28) show the alpha often lands INTRADAY, past that
    exit. If the caller also supplies the same-day CLOSE moves, this records a PARALLEL
    idio_close so the two horizons accrue side by side and the exit rule can be decided on
    evidence, not intuition. It never feeds the live verdict or the kill-switches."""
    entry = _find_entry(ledger_path, entry_id)
    if entry is None:
        raise ValueError(f"no entry with id {entry_id!r} in {ledger_path}")
    # MARKET-MODEL abnormal return (v1.5.3). Previously beta was hard-assumed = 1, i.e.
    # idio = stock - etf. That mis-attributes return for any stock whose beta isn't 1 —
    # which is most of them. A high-beta semi on a -3% sector day is charged -3% of "its own"
    # move when the correct charge is beta x -3%. With beta supplied, use AR = R - beta*R_mkt
    # (Kothari & Warner market model, alpha assumed 0 over a 1-day window). Without it, fall
    # back to beta=1 and FLAG the row so the two methods are never silently mixed.
    beta_used = 1.0 if beta is None else float(beta)
    idio = stock_open_pct - beta_used * etf_open_pct
    action = entry["verdict"]["action"]
    pred = +1 if action == "BUY" else (-1 if action == "SHORT" else 0)
    correct = None
    if pred != 0 and _sign(idio) != 0:
        correct = (_sign(idio) == pred)
    circular = (benchmark_weight_pct is not None
                and benchmark_weight_pct > BENCH_DOMINANCE_MAX_PCT)
    idio_close = None
    close_correct = None
    if stock_close_pct is not None and etf_close_pct is not None:
        idio_close = round(stock_close_pct - beta_used * etf_close_pct, 3)
        if pred != 0 and _sign(idio_close) != 0:
            close_correct = (_sign(idio_close) == pred)
    rec = {"type": "outcome", "entry_id": entry_id, "schema": SCHEMA, "logged_at": _now(),
           "ticker": entry["ticker"], "stock_open_pct": stock_open_pct,
           "etf_open_pct": etf_open_pct, "idio_open_pct": round(idio, 3),
           "predicted_sign": pred, "idio_sign_correct": correct,
           "idio_close_pct": idio_close, "close_sign_correct": close_correct,
           "classification": classification, "taxonomy": taxonomy, "note": note,
           "benchmark": benchmark, "benchmark_weight_pct": benchmark_weight_pct,
           "benchmark_circular": circular,
           "beta_used": beta_used, "beta_estimated": beta is not None,
           "method": ("market-model AR = R - beta*R_mkt (beta ESTIMATED, alpha=0, 1-day window); "
                      "NOT a full event study — no estimation-window test statistic"
                      if beta is not None else
                      "market-adjusted (beta ASSUMED = 1 — fallback, flagged); NOT an event study")}
    if circular:
        rec["note"] = (note + " | " if note else "") + (
            f"CIRCULAR BENCHMARK: {entry['ticker']} is {benchmark_weight_pct:.1f}% of "
            f"{benchmark} (> {BENCH_DOMINANCE_MAX_PCT}%) — idio return is understated; "
            f"re-benchmark against an equal-weight or ex-name index before using this row")
    _append(ledger_path, rec)
    return rec


# --------------------------------------------------------------------- overrides
def log_override(ticker: str, mechanical: str, taken: str, rationale: str,
                 entry_id: Optional[str] = None, event_date: Optional[str] = None,
                 ledger_path: Path = DEFAULT_LEDGER) -> dict:
    """PLUMBING rule (v1.5.0): ANY narrative override of a mechanical signal MUST be logged
    here and is scored as a decision in its own right. An unlogged override is how a model's
    real track record silently diverges from its measured one.

    mechanical : what the model actually said (e.g. "NO_TRADE").
    taken      : what was actually done (e.g. "SHORT MED").
    rationale  : the narrative reason, in the operator's own words.

    Score it later with record_override_outcome(); until then it sits in `overrides()`
    as an open, visible discrepancy."""
    rec = {"type": "override", "schema": SCHEMA, "logged_at": _now(),
           "engine_version": ENGINE_VERSION, "ticker": ticker,
           "event_date": event_date or _now()[:10], "entry_id": entry_id,
           "mechanical": mechanical, "taken": taken, "rationale": rationale,
           "override_id": f"OVR:{ticker}:{event_date or _now()[:10]}",
           "idio_open_pct": None, "override_helped": None}
    _append(ledger_path, rec)
    return rec


def record_override_outcome(override_id: str, idio_open_pct: float,
                            note: str = "", ledger_path: Path = DEFAULT_LEDGER) -> dict:
    """Score a logged override: did deviating from the mechanical signal help or hurt?
    Append-only — the LAST row per override_id wins."""
    src = None
    for r in _read(ledger_path):
        if r.get("type") == "override" and r.get("override_id") == override_id:
            src = r
    if src is None:
        raise ValueError(f"no override with id {override_id!r} in {ledger_path}")
    took = +1 if src["taken"].upper().startswith("BUY") else \
           (-1 if src["taken"].upper().startswith("SHORT") else 0)
    mech = +1 if src["mechanical"].upper().startswith("BUY") else \
           (-1 if src["mechanical"].upper().startswith("SHORT") else 0)
    s = _sign(idio_open_pct)
    took_pnl = took * s          # +1 right, -1 wrong, 0 flat/no-position
    mech_pnl = mech * s
    rec = {"type": "override", "schema": SCHEMA, "logged_at": _now(),
           "override_id": override_id, "ticker": src["ticker"],
           "event_date": src["event_date"], "entry_id": src.get("entry_id"),
           "mechanical": src["mechanical"], "taken": src["taken"],
           "rationale": src["rationale"], "idio_open_pct": round(idio_open_pct, 3),
           "override_helped": (took_pnl > mech_pnl) if took_pnl != mech_pnl else None,
           "note": note}
    _append(ledger_path, rec)
    return rec


def overrides(ledger_path: Path = DEFAULT_LEDGER) -> dict:
    """Latest state per override_id + a hit-rate on the ones that have been scored."""
    latest = {}
    for r in _read(ledger_path):
        if r.get("type") == "override":
            latest[r["override_id"]] = r
    scored = [r for r in latest.values() if r.get("override_helped") is not None]
    helped = sum(1 for r in scored if r["override_helped"])
    return {"n": len(latest), "n_scored": len(scored), "n_helped": helped,
            "helped_rate": (helped / len(scored)) if scored else None,
            "open": [k for k, r in latest.items() if r.get("idio_open_pct") is None],
            "rows": list(latest.values())}


def _find_entry(ledger_path, entry_id):
    for r in _read(ledger_path):
        if r.get("type") == "entry" and r.get("id") == entry_id:
            return r
    return None


